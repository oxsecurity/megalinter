class PluginFetchError(Exception):
    pass


def today():
    return datetime.datetime.now(datetime.timezone.utc).date().isoformat()


def plugin_slug(name):
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def raw_descriptor_url(url):
    match = GITHUB_BLOB_URL_REGEX.match(url)
    if match:
        return f"https://raw.githubusercontent.com/{match.group(1)}/{match.group(2)}/{match.group(3)}"
    return url


def github_repository(url):
    match = GITHUB_REPOSITORY_URL_REGEX.match(url)
    if match:
        return f"{match.group(1)}/{match.group(2)}"
    return None


def plugin_lock_url(raw_url):
    return raw_url.removesuffix(DESCRIPTOR_SUFFIX) + PLUGIN_LOCK_SUFFIX


# Same rules as plugin_factory.load_plugin, which refuses the other URLs
def plugin_url_errors(url):
    errors = []
    if not url.startswith("https://"):
        errors.append(f"The descriptor URL must start with https:// ({url})")
    if PLUGIN_FOLDER_MARKER not in url:
        errors.append(
            f"The descriptor must be hosted in a folder containing {PLUGIN_FOLDER_MARKER} ({url})"
        )
    if not url.endswith(DESCRIPTOR_SUFFIX):
        errors.append(
            f"The descriptor file name must end with {DESCRIPTOR_SUFFIX} ({url})"
        )
    return errors


def http_get(url, retries=3):
    response = config.http_get_with_retry(url, retries=retries)
    return response.status_code, response.text


@functools.lru_cache(maxsize=1)
def core_inventory():
    linter_keys = set()
    file_names = set()
    for descriptor_file in linter_factory.list_descriptor_files():
        file_names.add(os.path.basename(descriptor_file))
        with open(descriptor_file, "r", encoding="utf-8") as f:
            descriptor = yaml.load(f, Loader=DESCRIPTOR_YAML_LOADER)
        descriptor_id = descriptor["descriptor_id"]
        for linter in descriptor.get("linters", []):
            linter_keys.add(
                linter.get("name")
                or descriptor_id + "_" + linter["linter_name"].upper().replace("-", "_")
            )
    return {
        "linter_keys": linter_keys,
        "file_names": file_names,
    }


@functools.lru_cache(maxsize=1)
def descriptor_schema_validator():
    with open(
        os.path.join(get_descriptor_dir(), "schemas", SCHEMA_FILE),
        "r",
        encoding="utf-8",
    ) as f:
        return jsonschema.Draft7Validator(json.load(f))


@functools.lru_cache(maxsize=1)
def native_validators():
    return load_runtime_names(), build_schema_validator()


def shorten(message):
    if len(message) <= MAX_ERROR_LENGTH:
        return message
    return message[: MAX_ERROR_LENGTH - 3] + "..."


def schema_errors(descriptor):
    errors = []
    for error in descriptor_schema_validator().iter_errors(descriptor):
        location = "/".join(str(part) for part in error.absolute_path) or "(root)"
        errors.append(shorten(f"{location}: {error.message}"))
    return sorted(errors)


def sarif_mode(linter):
    if linter.get("can_output_sarif") is not True:
        return None
    if linter.get("cli_sarif_args") or linter.get("sarif_default_output_file"):
        return "native"
    if linter.get("sarif_text_regex"):
        return "text"
    if linter.get("sarif_unified_diff") is True:
        return "unified_diff"
    if linter.get("sarif_whole_output") is True:
        return "whole_output"
    return None


def audit_native(spec):
    native = spec.native_install
    if native is None:
        return {"status": "missing", "platforms": [], "unsupported": {}, "errors": []}
    runtime_names, validator = native_validators()
    errors = [shorten(error) for error in validate_spec(spec, runtime_names, validator)]
    if not isinstance(native, dict):
        return {
            "status": "invalid",
            "platforms": [],
            "unsupported": {},
            "errors": errors,
        }
    # The descriptor comes from a community author: keep only well-formed values
    declared = native.get("platforms")
    platforms = sorted(
        {platform for platform in declared if isinstance(platform, str)}
        if isinstance(declared, list)
        else set()
    )
    declared_unsupported = native.get("unsupported")
    unsupported = (
        {
            platform: str(reason)
            for platform, reason in sorted(
                (platform, reason)
                for platform, reason in declared_unsupported.items()
                if isinstance(platform, str)
            )
        }
        if isinstance(declared_unsupported, dict)
        else {}
    )
    if errors:
        status = "invalid"
    elif set(platforms) == set(NATIVE_PLATFORMS):
        status = "ok"
    else:
        status = "partial"
    return {
        "status": status,
        "platforms": platforms,
        "unsupported": unsupported,
        "errors": errors,
    }


def linter_lock_status(spec, lock, lock_known=True):
    if not lock_known:
        return "unknown"
    if lock is None:
        return "none"
    if lock.get("format") != LOCK_FORMAT_VERSION or spec.native_install is None:
        return "stale"
    entry = (lock.get("linters") or {}).get(spec.key)
    if not isinstance(entry, dict):
        return "stale"
    try:
        expected = compute_spec_hash(resolve_native_install(spec))
    except (KeyError, TypeError, AttributeError):
        return "stale"
    return "fresh" if entry.get("spec_hash") == expected else "stale"


def audit_linter(descriptor, linter, core, lock, lock_known=True):
    descriptor_id = descriptor.get("descriptor_id") or ""
    resolved = linter_factory.resolve_linter_extends(linter)
    spec = NativeLinterSpec(descriptor_id, descriptor.get("install"), resolved, None)
    required_missing = []
    if spec.key in core["linter_keys"]:
        required_missing.append("linter_key_unique")
    native = audit_native(spec)
    if native["status"] in ["missing", "invalid"]:
        required_missing.append("native_install")
    sarif = sarif_mode(resolved)
    if sarif is None:
        required_missing.append("sarif")
    required_missing += [
        prop for prop in REQUIRED_LINTER_PROPERTIES if not resolved.get(prop)
    ]
    lock_status = linter_lock_status(spec, lock, lock_known)
    if lock_status == "stale":
        required_missing.append("native_lock_fresh")
    return spec.key, {
        "linter_name": resolved["linter_name"],
        "linter_url": resolved.get("linter_url"),
        "native": native,
        "sarif": sarif,
        "lock": lock_status,
        "required_missing": required_missing,
        "recommended_missing": [
            prop for prop in RECOMMENDED_LINTER_PROPERTIES if not resolved.get(prop)
        ],
    }


def audit_descriptor(descriptor, file_name, core, lock=None, lock_known=True):
    result = {"errors": [], "required_missing": [], "linters": {}}
    if not isinstance(descriptor, dict):
        result["errors"].append("The descriptor is not a YAML mapping")
        result["required_missing"].append("schema")
        return result
    result["descriptor_id"] = descriptor.get("descriptor_id")
    errors = schema_errors(descriptor)
    if errors:
        result["errors"] += errors
        result["required_missing"].append("schema")
    if file_name in core["file_names"]:
        result["required_missing"].append("descriptor_file_unique")
    for linter in descriptor.get("linters") or []:
        if not isinstance(linter, dict) or "linter_name" not in linter:
            continue
        # A malformed community descriptor must not stop the audit of the whole catalog
        try:
            key, linter_result = audit_linter(
                descriptor, linter, core, lock, lock_known
            )
        except Exception as e:
            result["errors"].append(
                shorten(f"linter {linter.get('linter_name')!r}: {e}")
            )
            if "schema" not in result["required_missing"]:
                result["required_missing"].append("schema")
            continue
        result["linters"][key] = linter_result
    return result


def plugin_lock_status(linters_audit, lock, lock_known=True):
    if not lock_known:
        return "unknown"
    if lock is None:
        return "none"
    if any(linter["lock"] != "fresh" for linter in linters_audit.values()):
        return "stale"
    return "fresh"


# The lock is optional: one attempt (no retry on 404), and a failure only makes its status
# unknown, the descriptor stays reachable. Returns (lock or None, whether the lock is known)
def fetch_plugin_lock(raw_url, get):
    try:
        status, text = get(plugin_lock_url(raw_url), 1)
    except RuntimeError:
        return None, False
    if status == 404:
        return None, True
    if status != 200:
        return None, False
    try:
        lock = json.loads(text)
    except json.JSONDecodeError:
        return {"format": None}, True
    return (lock if isinstance(lock, dict) else {"format": None}), True


# Descriptor stored with the results, for the documentation of the plugin
def json_safe(descriptor):
    try:
        return json.loads(json.dumps(descriptor, default=str))
    except (TypeError, ValueError):
        return None


def missing_requirements(plugin_audit):
    missing = [(None, item) for item in plugin_audit.get("required_missing", [])]
    for key, linter in sorted(plugin_audit.get("linters", {}).items()):
        missing += [(key, item) for item in linter["required_missing"]]
    return missing


def missing_recommendations(plugin_audit):
    missing = []
    if plugin_audit.get("lock") == "none" and plugin_audit.get("linters"):
        missing.append((None, "native_lock"))
    for key, linter in sorted(plugin_audit.get("linters", {}).items()):
        missing += [(key, item) for item in linter["recommended_missing"]]
    return missing


def requirement_label(item):
    if item in REQUIRED_CHECKS:
        return REQUIRED_CHECKS[item]["label"]
    if item in RECOMMENDED_PLUGIN_CHECKS:
        return RECOMMENDED_PLUGIN_CHECKS[item]
    return RECOMMENDED_LINTER_PROPERTIES.get(item, item)


def plugin_status(plugin_audit):
    required = [item for _scope, item in missing_requirements(plugin_audit)]
    if "url" in required or "schema" in required or not plugin_audit.get("linters"):
        return "invalid"
    if required:
        return "incomplete"
    return "ok"


# A descriptor that can not be fetched keeps its last audit: an outage is not a gap
def unreachable_result(base, previous, error):
    result = dict(previous or {})
    result.update(base)
    result["status"] = "unreachable"
    result["fetch_error"] = shorten(error)
    for name, default in [
        ("errors", []),
        ("required_missing", []),
        ("linters", {}),
        ("lock", "none"),
    ]:
        result.setdefault(name, default)
    return result


def check_plugin(entry, previous, get, date):
    url = entry["pluginUrl"]
    base = {
        "name": entry["name"],
        "descriptor_url": url,
        "repository": github_repository(url),
        "changed_at": date,
    }
    url_errors = plugin_url_errors(raw_descriptor_url(url))
    if url_errors:
        return {
            **base,
            "status": "invalid",
            "errors": url_errors,
            "required_missing": ["url"],
            "linters": {},
            "lock": "none",
        }
    raw_url = raw_descriptor_url(url)
    try:
        status, text = get(raw_url, 3)
        if status != 200:
            raise PluginFetchError(f"HTTP {status} on {raw_url}")
    except (PluginFetchError, RuntimeError) as e:
        return unreachable_result(base, previous, str(e))
    lock, lock_known = fetch_plugin_lock(raw_url, get)
    result = {
        **base,
        "raw_url": raw_url,
        "descriptor_sha256": hashlib.sha256(text.encode("utf-8")).hexdigest(),
        "last_success_at": date,
    }
    try:
        descriptor = yaml.load(text, Loader=DESCRIPTOR_YAML_LOADER)
    except yaml.YAMLError as e:
        result.update(
            {
                "errors": [shorten(f"Invalid YAML: {e}")],
                "required_missing": ["schema"],
                "linters": {},
                "lock": "none",
                "status": "invalid",
            }
        )
        return result
    audit = audit_descriptor(
        descriptor, raw_url.rsplit("/", 1)[1], core_inventory(), lock, lock_known
    )
    result.update(audit)
    if isinstance(descriptor, dict):
        result["descriptor"] = json_safe(descriptor)
    result["lock"] = plugin_lock_status(audit["linters"], lock, lock_known)
    result["status"] = plugin_status(result)
    return result


def without_dates(result):
    return {key: value for key, value in result.items() if key not in DATE_FIELDS}


# Results unchanged since the previous audit keep their dates: the audit file and the
# documentation change only when the results do
def audit_plugin(entry, previous=None, get=http_get, date=None):
    result = check_plugin(entry, previous, get, date or today())
    if previous is not None and without_dates(result) == without_dates(previous):
        return previous
    return result


def audit_catalog(plugins, previous_audit=None, get=http_get, date=None):
    previous_audit = previous_audit or {}
    return {
        plugin["name"]: audit_plugin(
            plugin, previous_audit.get(plugin["name"]), get, date
        )
        for plugin in plugins
    }


def load_audit_file(path):
    if not os.path.isfile(path):
        return {}
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f).get("plugins", {})


def write_audit_file(path, plugins_audit):
    document = {"@generated": AUDIT_FILE_HEADER, "plugins": plugins_audit}
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        json.dump(document, f, indent=2, sort_keys=True)
        f.write("\n")
