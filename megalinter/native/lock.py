import hashlib
import json
import os

from megalinter.native.context import NativeError
from megalinter.utils import get_descriptor_dir

LOCK_FORMAT_VERSION = 1
LOCK_HEADER = "automatically @generated by .automation/native_lock.py - do not edit"


def locks_dir(descriptor_dir=None):
    return os.path.join(descriptor_dir or get_descriptor_dir(), "native-locks")


def lock_path(key, descriptor_dir=None):
    return os.path.join(locks_dir(descriptor_dir), key + ".json")


def compute_spec_hash(resolved_native_install):
    canonical = json.dumps(
        resolved_native_install, sort_keys=True, separators=(",", ":")
    )
    return hashlib.sha256(canonical.encode("utf-8")).hexdigest()


def load_lock(key, descriptor_dir=None):
    path = lock_path(key, descriptor_dir)
    if not os.path.isfile(path):
        raise NativeError(f"No native lock for {key}: run `make native-lock`")
    with open(path, "r", encoding="utf-8") as f:
        lock = json.load(f)
    if lock.get("format") != LOCK_FORMAT_VERSION:
        raise NativeError(f"Unsupported lock format for {key}: {lock.get('format')}")
    return lock


def check_lock_fresh(key, resolved_native_install, lock):
    if lock.get("spec_hash") != compute_spec_hash(resolved_native_install):
        raise NativeError(
            f"The native lock of {key} is stale (its descriptor changed): "
            "native install is temporarily unavailable for this linter"
        )


def runtime_lock_path(name, descriptor_dir=None):
    return os.path.join(locks_dir(descriptor_dir), "runtimes", name + ".json")


def load_runtime_lock(name, descriptor_dir=None):
    path = runtime_lock_path(name, descriptor_dir)
    if not os.path.isfile(path):
        raise NativeError(f"No native lock for runtime {name}: run `make native-lock`")
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


def platform_lock(lock, platform):
    entry = (lock.get("platforms") or {}).get(platform)
    if entry is None:
        raise NativeError(
            f"The native lock of {lock.get('linter')} has no {platform} entry"
        )
    return entry


def write_lock(key, lock, descriptor_dir=None):
    os.makedirs(locks_dir(descriptor_dir), exist_ok=True)
    document = {"@generated": LOCK_HEADER, "format": LOCK_FORMAT_VERSION, **lock}
    with open(lock_path(key, descriptor_dir), "w", encoding="utf-8", newline="\n") as f:
        json.dump(document, f, indent=2, sort_keys=True)
        f.write("\n")
